#!/bin/bash
# One-time setup: keeps the DocCheck scanner server running in the
# background, so the "Scan Again" button always works - even if you
# open index.html by double-clicking it.
#
# How: puts launch-server.vbs into your Windows Startup folder,
# so a tiny hidden server starts every time you log on.
#
# Run once inside Git Bash:
#   bash setup-scanserver.sh
#
# Uninstall any time: choose option 2 below.

echo "DocCheck Scan Server Installer"
echo "=============================="
echo ""
echo "This places a tiny starter into your Windows Startup folder."
echo "A hidden mini-server will then run in the background, and the"
echo "\"Scan Again\" button re-runs health.sh by itself - no commands."
echo ""

FOLDER=$(cd "$(dirname "$0")" && pwd)

STARTUP_WIN=$(powershell.exe -NoProfile -Command "[Environment]::GetFolderPath('Startup')" < /dev/null 2>/dev/null | tr -d '\r')
if [ -n "$STARTUP_WIN" ]; then
  STARTUP=$(cygpath -u "$STARTUP_WIN" 2>/dev/null || wslpath -u "$STARTUP_WIN" 2>/dev/null || echo "$STARTUP_WIN")
else
  STARTUP="/mnt/c/Users/$USER/AppData/Roaming/Microsoft/Windows/Start Menu/Programs/Startup"
  STARTUP_WIN="C:\\Users\\$USER\\AppData\\Roaming\\Microsoft\\Windows\\Start Menu\\Programs\\Startup"
fi

if [ -z "$STARTUP" ] || [ ! -d "$STARTUP" ]; then
  echo "Could not locate your Startup folder ($STARTUP). Nothing changed."
  exit 1
fi

echo "  1) Install (server auto-starts at every log on)"
echo "  2) Remove (uninstall)"
echo ""
read -p "Choose 1 or 2: " CHOICE

case $CHOICE in
  1)
    {
      echo "' Auto-generated by setup-scanserver.sh - do not edit"
      echo "' Starts the DocCheck mini-server fully hidden."
      echo "Set sh = CreateObject(\"WScript.Shell\")"
      echo "sh.Run \"powershell.exe -NoProfile -ExecutionPolicy Bypass -File \"\"@BASE@\\server.ps1\"\"\", 0, False"
    } | sed "s|@BASE@|$WINFOLDER|" > "$STARTUP/DocCheckServer.vbs" && {
      # start it right now too, no need to log off
      wscript.exe "$STARTUP_WIN\\DocCheckServer.vbs" < /dev/null 2>/dev/null
      sleep 2
      echo ""
      echo "Done! The scanner server is running in the background."
      echo "Press \"Scan Again\" on the dashboard - it rescans now."
      echo ""
      echo "To undo later, run this script again and choose 2,"
      echo "or just delete: $STARTUP_WIN\\DocCheckServer.vbs"
    } || echo "Copy failed. Nothing changed."
    ;;
  2)
    rm -f "$STARTUP/DocCheckServer.vbs"
    echo "Removed. The server will no longer start at log on."
    ;;
  *)
    echo "Nothing changed."
    ;;
esac
